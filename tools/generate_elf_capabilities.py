"""Retain ordered capability tables from the immutable test oracle."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=(ROOT/'upstream/src/readelf.c').read_text();header=(ROOT/'upstream/src/readelf.h').read_text()
constants={name:int(value,16) for name,value in re.findall(r'^#define\s+(AV_\w+)\s+(0x[0-9a-fA-F]+)',header,re.M)}
notice=source[:source.index('*/')+2]
text=notice+'\n// SPDX-License-Identifier: GPL-3.0-only\n// Generated by tools/generate_elf_capabilities.py; retain upstream notices.\n'
tables={}
for arch in ['sparc','386']:
    block=re.search(r'cap_desc_'+arch+r'\[\]\s*=\s*\{(.*?)\n\};',source,re.S).group(1)
    entries=[(constants[key],label) for key,label in re.findall(r'\{\s*(AV_\w+),\s*"([^"]+)"',block)]
    tables[arch]=entries
    text+=f'pub(super) const CAP_{arch.upper()}: &[(u64,&str)] = &[\n'
    text+=''.join(f'    ({mask:#x},"{label}"),\n' for mask,label in entries)+'];\n'
(ROOT/'src/elf_capabilities.rs').write_text(text)
(ROOT/'reports/elf-capability-tables.json').write_text(json.dumps(dict(upstream_commit=json.loads((ROOT/'data/UPSTREAM.json').read_text())['commit'],readelf_c_sha256=hashlib.sha256(source.encode()).hexdigest(),readelf_h_sha256=hashlib.sha256(header.encode()).hexdigest(),tables=tables),indent=2)+'\n')
